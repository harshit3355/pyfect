import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from zoneinfo import TZPATH

import pytest

from pyfect import date_time
from pyfect.date_time._icu_zones import (
    CANONICAL,
    DATA,
    ICU_VERSION,
    NODE_VERSION,
    TZ_ZONES,
    TZIF,
)
from pyfect.date_time._zones import resolved_zone_id

_ROOT = Path(__file__).parent.parent.parent


@pytest.mark.parametrize(
    ("written", "canonical"),
    [
        ("Asia/Kolkata", "Asia/Calcutta"),
        ("asia/kolkata", "Asia/Calcutta"),
        ("EST", "America/Panama"),
        ("Etc/UTC", "UTC"),
        ("GMT", "UTC"),
        ("Zulu", "UTC"),
        ("Europe/Kyiv", "Europe/Kiev"),
        ("Asia/Kathmandu", "Asia/Katmandu"),
        ("PST", "America/Los_Angeles"),
        ("IST", "Asia/Calcutta"),
        ("US/Pacific-New", "America/Los_Angeles"),
        ("America/Ciudad_Juarez", "America/Ciudad_Juarez"),
        ("SYSTEMV/AST4ADT", "SystemV/AST4ADT"),
        ("Etc/GMT+5", "Etc/GMT+5"),
        ("+05:30", "+05:30"),
        ("+0530", "+05:30"),
        ("+05", "+05:00"),
        ("-00:00", "+00:00"),
        ("\u221205:00", "-05:00"),
    ],
)
def test_zone_ids_read_as_under_node(written: str, canonical: str) -> None:
    # Node 24.22.1: new Intl.DateTimeFormat("en-US", {timeZone: written}).resolvedOptions().timeZone
    zone = date_time.zone_named(written)
    assert zone is not None
    assert resolved_zone_id(zone) == canonical
    same_but_case = canonical.lower() == written.lower() or written[0] in "+-\u2212"
    assert date_time.zone_to_string(zone) == (canonical if same_but_case else written)
    resolved = date_time.zone_named(canonical)
    assert zone == resolved
    assert hash(zone) == hash(resolved)
    assert zone is date_time.zone_named(written)


