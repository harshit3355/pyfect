"""Zone ids as Node's ``Intl`` (ICU) resolves them: Effect's ``zoneMakeNamed``
keeps the id it is given (taking ``resolvedOptions().timeZone``'s casing when
the two differ only in case) and compares zones by the resolved id.

``date_time._icu_zones`` is generated by ``scripts/gen_icu_zones.py`` from
Node; when the machine's Node is the recorded version, every id is checked
against it again.
"""

